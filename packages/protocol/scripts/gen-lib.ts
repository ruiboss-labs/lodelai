/**
 * TS 프로토콜 생성 부품(U1, #52) — 이 패키지의 생성기(`gen.ts`, 선 스키마만)와 비공개 쪽 생성기가 같이 쓴다(오픈 코어 준비 ①, #570).
 * 어떤 스키마를 어디에 만들지는 부르는 쪽이 정한다.
 *
 * - `<schemaDir>/<name>.schema.json` → `<outDir>/<name>.ts` (json-schema-to-typescript). 파일마다 모듈 하나라
 *   `ws.Hello`·`ipc.Hello` 같은 같은 이름이 충돌하지 않는다. 다른 파일의 정의는 복제하지 않고 `import type` 으로 잇는다
 *   (`./<file>.ts` — 다른 패키지 것이면 부르는 쪽이 그 자리에 다시 내보내는 파일을 둔다).
 * - 포맷은 뒤이어 Biome 이 맡는다(`bun run protocol:gen` 이 `biome format --write` 를 부른다).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { compile, type JSONSchema } from 'json-schema-to-typescript'

/** 생성 파일 머리. `generator` 는 만든 스크립트 경로. */
export function banner(generator: string): string {
  return `// @generated by ${generator} — 손으로 고치지 않는다.\n// 원본: packages/protocol/schema. 다시 만들기: \`bun run protocol:gen\`.\n`
}

type Json = null | boolean | number | string | Json[] | { [k: string]: Json }

/** `$defs` → `definitions`, 파일 안 `$ref` 는 `#/definitions/X`, 다른 파일 `$ref` 는 `tsType` 으로 바꾸고 import 를 모은다. */
function rewrite(node: Json, file: string, imports: Map<string, Set<string>>): Json {
  if (Array.isArray(node)) return node.map((x) => rewrite(x, file, imports))
  if (node === null || typeof node !== 'object') return node
  const ref = node.$ref
  if (typeof ref === 'string') {
    const [f = '', frag = ''] = ref.split('#')
    const name = frag.replace('/$defs/', '')
    if (f === '' || f === file) return { ...node, $ref: `#/definitions/${name}` }
    const mod = f.replace('.schema.json', '')
    if (!imports.has(mod)) imports.set(mod, new Set())
    imports.get(mod)?.add(name)
    const { $ref: _ignored, ...rest } = node
    return { ...rest, tsType: `${pascal(mod)}${name}` }
  }
  const out: { [k: string]: Json } = {}
  for (const [k, v] of Object.entries(node)) out[k] = rewrite(v, file, imports)
  return out
}

/** `request_box` → `RequestBox`(밑줄 마디마다 대문자). */
function pascal(s: string): string {
  return s
    .split('_')
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('')
}

export async function genSchema(schemaDir: string, name: string, generator: string): Promise<string> {
  const file = `${name}.schema.json`
  const schema = JSON.parse(readFileSync(join(schemaDir, file), 'utf8')) as { [k: string]: Json }
  const imports = new Map<string, Set<string>>()
  const defs = rewrite(schema.$defs ?? {}, file, imports) as { [k: string]: Json }
  // 루트는 모든 정의를 가리키는 자리표시. 생성 뒤 지운다.
  const rootSchema = {
    title: 'LodelaiGeneratedRoot',
    type: 'object',
    properties: Object.fromEntries(Object.keys(defs).map((k) => [k, { $ref: `#/definitions/${k}` }])),
    additionalProperties: false,
    definitions: defs,
  }
  let ts = await compile(rootSchema as unknown as JSONSchema, name, {
    bannerComment: '',
    additionalProperties: false,
    strictIndexSignatures: true,
    unknownAny: true,
    format: false,
    declareExternallyReferenced: true,
    enableConstEnums: false,
    $refOptions: { resolve: { external: false } },
  })
  ts = ts.replace(/export interface LodelaiGeneratedRoot \{[\s\S]*?\n\}\n/, '')
  const importLines = [...imports.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([mod, names]) => {
      const list = [...names]
        .sort()
        .map((n) => `${n} as ${pascal(mod)}${n}`)
        .join(', ')
      return `import type { ${list} } from './${mod}.ts'`
    })
  return `${banner(generator)}\n${importLines.join('\n')}${importLines.length ? '\n\n' : ''}${ts}`
}

/** 상수 파일들(`files`)을 TS 상수로. 이름이 겹치면 실패. `prelude` 는 앞에 넣을 줄(다른 패키지 상수 다시 내보내기 등). */
export function genConstants(schemaDir: string, files: readonly string[], generator: string, prelude = ''): string {
  const seen = new Set<string>()
  const lines: string[] = []
  for (const file of files) {
    const c = JSON.parse(readFileSync(join(schemaDir, file), 'utf8')) as Record<string, unknown>
    for (const [k, v] of Object.entries(c)) {
      if (k.startsWith('$')) continue
      if (seen.has(k)) throw new Error(`상수 ${k} 가 두 파일에 다 있다`)
      seen.add(k)
      lines.push(`export const ${k} = ${JSON.stringify(v)}`)
    }
  }
  return `${banner(generator)}// packages/protocol/schema/${files.join(' + ')}\n\n${prelude}${lines.join('\n')}\n`
}

/** 스키마들 + 상수를 `outDir` 에 쓴다. */
export async function generate(opts: {
  schemaDir: string
  outDir: string
  schemas: readonly string[]
  constants: string
  generator: string
}): Promise<number> {
  for (const name of opts.schemas) {
    writeFileSync(join(opts.outDir, `${name}.ts`), await genSchema(opts.schemaDir, name, opts.generator))
  }
  writeFileSync(join(opts.outDir, 'constants.ts'), opts.constants)
  return opts.schemas.length + 1
}
