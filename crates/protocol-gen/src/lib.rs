/// 폴더(인자 `--schema-dir`·`--fixture-dir`·`--out-dir` 로 바꿈, 기본은 레포 루트 기준 — 출력 폴더 기본은 부르는 쪽이).
pub struct Dirs {
    pub schema: PathBuf,
    pub fixture: PathBuf,
    pub out: PathBuf,
}

impl Dirs {
    #[must_use]
    pub fn from_args(args: &[String], out_default: &str) -> Self {
        let arg = |name: &str, default: &str| {
            args.iter()
                .position(|a| a == name)
                .and_then(|i| args.get(i + 1))
                .map_or_else(|| PathBuf::from(default), PathBuf::from)
        };
        Self {
            schema: arg("--schema-dir", "packages/protocol/schema"),
            fixture: arg("--fixture-dir", "packages/protocol/fixtures"),
            out: arg("--out-dir", out_default),
        }
    }
}

/// 상태 스키마 묶음: (스키마 정의 이름, 크레이트 안 경로, 원본 설명, 값들).
pub type StateDefs = Vec<(&'static str, &'static str, String, Vec<&'static str>)>;

/// 생성 파일 머리. `generator` 는 만든 크레이트(`lodelai-protocol-gen (crates/protocol-gen)` 꼴).
#[must_use]
pub fn header(generator: &str) -> String {
    format!("// @generated by {generator} — 손으로 고치지 않는다.\n// 원본: packages/protocol/schema. 다시 만들기: `bun run protocol:gen`.\n\n")
}

/// 생성 enum(`ALL`·`as_str`)의 값 이름들.
pub fn names<T: Copy>(all: &[T], f: impl Fn(T) -> &'static str) -> Vec<&'static str> {
    all.iter().map(|x| f(*x)).collect()
}

