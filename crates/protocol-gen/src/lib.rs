/// # Panics
/// 파일을 못 읽거나 JSON 이 아니면.
#[must_use]
pub fn read_json(p: &Path) -> Value {
    let text = std::fs::read_to_string(p).unwrap_or_else(|e| panic!("{}: {e}", p.display()));
    serde_json::from_str(&text).unwrap_or_else(|e| panic!("{}: {e}", p.display()))
}

/// 생성물 쓰기 — `check` 면 쓰지 않고 오래된 것만 모은다.
pub struct Writer {
    check: bool,
    stale: Vec<PathBuf>,
}

impl Writer {
    #[must_use]
    pub fn new(check: bool) -> Self {
        Self {
            check,
            stale: Vec::new(),
        }
    }

    /// 결과를 찍고 종료 코드(`check` 인데 오래된 것이 있으면 실패).
    #[must_use]
    pub fn finish(self, name: &str) -> ExitCode {
        if self.stale.is_empty() {
            println!("{name}: 최신");
            return ExitCode::SUCCESS;
        }
        for p in &self.stale {
            println!(
                "{} {}",
                if self.check { "오래됨:" } else { "갱신:" },
                p.display()
            );
        }
        if self.check {
            eprintln!("{name}: 생성물이 오래됐습니다. `bun run protocol:gen` 후 커밋하세요.");
            ExitCode::FAILURE
        } else {
            ExitCode::SUCCESS
        }
    }

    /// 텍스트 파일: 바이트가 다르면 쓴다.
    pub fn text(&mut self, path: &Path, content: &str) {
        if std::fs::read_to_string(path).ok().as_deref() == Some(content) {
            return;
        }
        self.stale.push(path.to_owned());
        if !self.check {
            std::fs::write(path, content).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        }
    }

    /// JSON 파일: 의미가 다를 때만 쓴다(포맷은 Biome).
    pub fn json(&mut self, path: &Path, value: &Value) {
        if std::fs::read_to_string(path)
            .ok()
            .and_then(|t| serde_json::from_str::<Value>(&t).ok())
            .as_ref()
            == Some(value)
        {
            return;
        }
        self.stale.push(path.to_owned());
        if !self.check {
            let text = serde_json::to_string_pretty(value).expect("json") + "\n";
            std::fs::write(path, text).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        }
    }
}

/// `\p{…}`(Unicode 속성)가 든 `pattern` 은 regress 를 `u` 플래그로 만든다 — JSON Schema 의 ECMA-262 정규식은 `u` 없이는
/// `\p` 를 글자로 읽는다(묶음 29 §6 세션용 주소의 서버 칸 `\p{L}`). 그 밖의 정규식은 그대로.
fn unicode_patterns(code: &str) -> String {
    const NEW: &str = "::regress::Regex::new(";
    let mut out = String::with_capacity(code.len());
    let mut rest = code;
    while let Some(at) = rest.find(NEW) {
        out.push_str(&rest[..at]);
        // 인자는 문자열 리터럴 하나(prettyplease 가 줄을 접을 수 있다): `(` 공백 `"…"` 공백 `,`? 공백 `)`.
        let after = &rest[at + NEW.len()..];
        let open = after.find('"').expect("Regex::new 여는 따옴표");
        let close = open + 1 + after[open + 1..].find('"').expect("Regex::new 닫는 따옴표");
        let lit = &after[open..=close];
        let paren = close + after[close..].find(')').expect("Regex::new 닫는 괄호");
        if lit.contains("\\p{") {
            out.push_str(&format!("::regress::Regex::with_flags({lit}, \"u\")"));
        } else {
            out.push_str(&rest[at..at + NEW.len() + paren + 1]);
        }
        rest = &after[paren + 1..];
    }
    out.push_str(rest);
    out
}

// ------------------------------------------------------------------ 스키마 전처리

/// `request_box` → `RequestBox`(밑줄 마디마다 대문자).
fn pascal(stem: &str) -> String {
    stem.split('_')
        .map(|p| {
            let mut c = p.chars();
            c.next()
                .map(|f| f.to_uppercase().collect::<String>() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}

/// 속성 이름 → 스키마인 맵. 이 맵의 **키**는 키워드가 아니므로 지우거나 바꾸지 않는다
/// (속성 이름이 `format`·`const` 여도 그대로 둔다).
const SCHEMA_MAPS: &[&str] = &["properties", "definitions", "$defs", "patternProperties"];

/// 전처리. 외부 참조는 `ext` 에 (자리표시 이름 → (모듈, 원래 이름)) 으로 모은다.
fn rewrite(v: &mut Value, file: &str, ext: &mut BTreeMap<String, (String, String)>) {
    match v {
        Value::Object(m) => {
            m.remove("format");
            if let Some(c) = m.remove("const") {
                let ty = match &c {
                    Value::String(_) => Some("string"),
                    Value::Number(n) if n.is_i64() || n.is_u64() => Some("integer"),
                    Value::Bool(_) => Some("boolean"),
                    _ => None,
                };
                if let Some(ty) = ty {
                    m.entry("type").or_insert_with(|| Value::String(ty.into()));
                }
                m.insert("enum".into(), Value::Array(vec![c]));
            }
            if let Some(Value::String(r)) = m.get_mut("$ref") {
                let (f, frag) = r.split_once('#').expect("$ref 에 # 없음");
                let name = frag
                    .strip_prefix("/$defs/")
                    .expect("$ref 는 #/$defs/ 만")
                    .to_owned();
                if f.is_empty() || f == file {
                    *r = format!("#/definitions/{name}");
                } else {
                    let stem = f.strip_suffix(".schema.json").expect("스키마 파일 이름");
                    let local = format!("Ext{}{}", pascal(stem), name);
                    ext.insert(local.clone(), (stem.to_owned(), name));
                    *r = format!("#/definitions/{local}");
                }
            }
            for (k, x) in m.iter_mut() {
                if SCHEMA_MAPS.contains(&k.as_str()) {
                    rewrite_map(x, file, ext);
                } else {
                    rewrite(x, file, ext);
                }
            }
        }
        Value::Array(a) => a.iter_mut().for_each(|x| rewrite(x, file, ext)),
        _ => {}
    }
}

/// 이름 → 스키마 맵: 키는 그대로, 값만 스키마로 전처리.
fn rewrite_map(v: &mut Value, file: &str, ext: &mut BTreeMap<String, (String, String)>) {
    if let Value::Object(m) = v {
        for (_, x) in m.iter_mut() {
            rewrite(x, file, ext);
        }
    } else {
        rewrite(v, file, ext);
    }
}

/// `<schema>/<stem>.schema.json` → typify Rust 모듈.
///
/// # Panics
/// 스키마가 잘못됐거나 typify 가 못 받으면.
#[must_use]
pub fn gen_rust(schema_dir: &Path, stem: &str, generator: &str) -> String {
    let file = format!("{stem}.schema.json");
    let mut schema = read_json(&schema_dir.join(&file));
    let mut defs = schema
        .as_object_mut()
        .and_then(|o| o.remove("$defs"))
        .unwrap_or_else(|| panic!("{file}: $defs 없음"));
    let mut ext = BTreeMap::new();
    rewrite_map(&mut defs, &file, &mut ext);

    let mut settings = typify::TypeSpaceSettings::default();
    settings.with_struct_builder(false);
    let defs_obj = defs.as_object_mut().expect("$defs 는 객체");
    for (local, (module, name)) in &ext {
        // 이름 붙은 타입이 되도록 enum 자리표시를 둔다(단순 string 은 typify 가 인라인해 replacement 가 안 걸린다).
        defs_obj.insert(
            local.clone(),
            json!({"type": "string", "enum": ["__lodelai_placeholder"]}),
        );
        settings.with_replacement(
            local.as_str(),
            format!("super::{module}::{name}").as_str(),
            std::iter::empty(),
        );
    }
    let root = json!({"$schema": "http://json-schema.org/draft-07/schema#", "definitions": defs});
    let root: schemars::schema::RootSchema =
        serde_json::from_value(root).expect("schemars RootSchema");
    let mut space = typify::TypeSpace::new(&settings);
    space
        .add_root_schema(root)
        .unwrap_or_else(|e| panic!("{file}: typify: {e}"));
    let ast = syn::parse2::<syn::File>(space.to_stream()).expect("typify 출력 파싱");
    format!(
        "{}{}",
        header(generator),
        unicode_patterns(&prettyplease::unparse(&ast))
    )
}

/// `krate`(생성 statechart 크레이트)의 enum 을 스키마 이름으로 다시 내보내는 모듈.
#[must_use]
pub fn gen_states_rs(
    defs: &StateDefs,
    krate: &str,
    stem: &str,
    yaml: &str,
    generator: &str,
) -> String {
    let mut s = header(generator);
    s.push_str(&format!("//! 상태 enum — `{krate}`({yaml} 에서 build.rs 로 생성)를 그대로 다시 내보낸다.\n//! 스키마 이름({stem}.schema.json `$defs`)과 Rust 경로의 대응. 직렬화 표기는 yaml 이름(snake_case).\n\n"));
    for (name, path, _, _) in defs {
        s.push_str(&format!("pub use {krate}::{path} as {name};\n"));
    }
    s
}

/// 상태 enum 값 → JSON Schema(TS 가 이걸로 생성한다).
#[must_use]
pub fn gen_states_schema(types: &StateDefs, stem: &str, yaml: &str, krate: &str) -> Value {
    let mut defs = Map::new();
    for (name, _, src, values) in types {
        defs.insert(
            (*name).into(),
            json!({"type": "string", "enum": values, "description": src}),
        );
    }
    json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": format!("{stem}.schema.json"),
        "title": format!("상태 enum — {yaml} 에서 생성 (손으로 고치지 않는다)"),
        "$comment": format!("GENERATED by lodelai-protocol-gen: {krate}(= {yaml}) 의 enum 값에서 만든다. Rust 는 {krate} 를 re-export 하고, TS 는 이 파일에서 생성한다."),
        "$defs": defs,
    })
}

/// 상수 파일들(`files`, 스키마 폴더 기준)을 한 맵으로. 이름이 겹치면 실패.
///
/// # Panics
/// 파일이 없거나 객체가 아니거나 이름이 겹치면.
#[must_use]
pub fn read_constants(schema_dir: &Path, files: &[&str]) -> Map<String, Value> {
    let mut all = Map::new();
    for f in files {
        for (k, v) in read_json(&schema_dir.join(f))
            .as_object()
            .expect("constants 는 객체")
        {
            if k.starts_with('$') {
                continue;
            }
            assert!(
                all.insert(k.clone(), v.clone()).is_none(),
                "상수 {k} 가 두 파일에 다 있다"
            );
        }
    }
    all
}

/// 상수 모듈. `doc` 은 모듈 문서 한 줄, `prelude` 는 상수 앞에 넣을 줄(다른 크레이트 상수 다시 내보내기 등).
///
/// # Panics
/// 지원하지 않는 값이면.
#[must_use]
pub fn gen_constants_rs(
    c: &Map<String, Value>,
    doc: &str,
    prelude: &str,
    generator: &str,
) -> String {
    let mut s = header(generator);
    s.push_str(&format!("//! {doc}\n\n{prelude}"));
    for (k, v) in c {
        match v {
            Value::Number(n) if n.is_i64() => {
                let ty = if k.starts_with("IPC_ERROR_") {
                    "i64"
                } else {
                    "u64"
                };
                s.push_str(&format!("pub const {k}: {ty} = {n};\n"));
            }
            Value::Number(n) if n.is_u64() => s.push_str(&format!("pub const {k}: u64 = {n};\n")),
            Value::String(t) => s.push_str(&format!("pub const {k}: &str = {t:?};\n")),
            Value::Bool(b) => s.push_str(&format!("pub const {k}: bool = {b};\n")),
            other => panic!("constants.{k}: 지원하지 않는 값 {other}"),
        }
    }
    s
}

/// `generated/mod.rs`: typify 모듈(`typed`, lint 끔) + 손쉬운 모듈(`plain`). `prelude` 는 그 앞 줄(다시 내보내기 등).
#[must_use]
pub fn gen_mod_rs(typed: &[&str], plain: &[&str], prelude: &str, generator: &str) -> String {
    let mut s = header(generator);
    s.push_str("//! 생성 모듈. rustfmt·clippy 는 생성물에 적용하지 않는다.\n\n");
    s.push_str(prelude);
    for m in typed {
        s.push_str(&format!(
            "#[rustfmt::skip]\n#[allow(clippy::all, clippy::pedantic, unused, unreachable_pub)]\npub mod {m};\n"
        ));
    }
    for m in plain {
        s.push_str(&format!("#[rustfmt::skip]\npub mod {m};\n"));
    }
    s
}

