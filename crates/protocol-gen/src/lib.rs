//! lodelai-protocol-gen 라이브러리 — 스키마 → Rust(typify)·상태 enum 다시 내보내기·상수·fixture 재서명의 공통 부품.
//! 이 크레이트의 생성기(bin, 선 스키마만)와 비공개 쪽 생성기가 같이 쓴다(오픈 코어 준비 ①, #570). 어떤 스키마를 어디에
//! 만들지는 부르는 쪽이 정한다 — 이 라이브러리는 파일 이름을 모른다.
//!
//! typify 에 넣기 전 스키마 전처리(의미는 같고 typify 가 못 받는 표기만 바꾼다):
//! - `$defs` → `definitions`(typify 는 Draft 7 모델), 파일 안 `$ref` 는 `#/definitions/X` 로.
//! - 다른 파일 `$ref` 는 자리표시 정의 `Ext<File><X>` + typify replacement `super::<file>::X` — 타입을 복제하지 않는다.
//!   그래서 부르는 쪽 `generated` 모듈에 그 파일 모듈이 있어야 한다(다른 크레이트 것이면 다시 내보내 둔다).
//! - `format` 삭제: `date-time` 이 chrono 로 바뀌면 서명이 걸린 시각 문자열 바이트가 보존되지 않는다(정규형 검사는 `pattern` 이 한다).
//! - `const` → 값 하나짜리 `enum`: typify 0.8 은 `const` 를 `serde_json::Value` 로 만들어 `kind`·`t` 판별이 사라진다
//!   (그러면 같은 필드를 가진 `ReplyMessage`·`RejectedMessage` 가 구분되지 않는다).
//!
//! JSON 출력(상태 스키마·fixtures)은 **의미가 바뀔 때만** 다시 쓴다 — 파일 포맷은 Biome 이 맡는다.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

